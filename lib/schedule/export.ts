  stt: string;
  startsAt: string;
  endsAt: string;
  duration: string;
  teamName: string;
  policyName: string;
  assigneeName: string;
  backupName: string;
  shiftStatus: string;
  confirmationStatus: string;
  source: string;
  checkInAt: string;
  checkOutAt: string;
  checkInPhotoUrl: string;
  checkOutPhotoUrl: string;
